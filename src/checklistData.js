// Helper to convert categories to a flat task array or map for Firestore storage
export const getInitialTasksArray = () => {
  const tasks = [];
  INITIAL_CATEGORIES.forEach((cat) => {
    cat.tasks.forEach((task) => {
      tasks.push({
        id: task.id,
        categoryId: cat.id,
        categoryNumber: cat.number,
        title: task.title,
        completed: Boolean(task.completed),
        updatedAt: new Date().toISOString(),
        updatedBy: "Initial Setup",
      });
    });
  });
  return tasks;
};

// Calculate metrics from tasks array
export const calculateChecklistMetrics = (tasks) => {
  const totalTasks = tasks.length;
  const completedTasks = tasks.filter((t) => t.completed).length;
  const remainingTasks = totalTasks - completedTasks;
  const percentage = totalTasks > 0 ? Math.round((completedTasks / totalTasks) * 100) : 0;
  return {
    totalTasks,
    completedTasks,
    remainingTasks,
    percentage,
  };
};
